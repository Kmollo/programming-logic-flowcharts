"""
This program builds a sentence from two variables and prints it.
    c holds the first animal in the phrase
    d holds the second animal in the phrase
    s combines c and d into the full message that is displayed
"""

c = "cats"                                    # first animal in the phrase
d = "dogs"                                    # second animal in the phrase
s = "It is raining " + c + " and " + d + "."  # full message built from c and d

print(s)                                      # display the finished sentence
